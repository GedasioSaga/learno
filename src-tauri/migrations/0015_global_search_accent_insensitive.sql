-- Esta migração não faz nada, e isso é o resultado da migração para SQLite.
--
-- Na versão Postgres ela existia para resolver um problema que o SQLite não
-- tem: fazer a busca global (FUN-037) achar "revisão" procurando por
-- "revisao". Lá isso custava `CREATE EXTENSION unaccent`, uma função
-- `immutable_unaccent` embrulhando `unaccent()` (que é STABLE, e Postgres
-- recusa STABLE dentro de coluna gerada ou índice de expressão), e a
-- reconstrução da coluna gerada e dos índices que 0004 havia criado — porque
-- a expressão de uma coluna gerada não pode ser alterada no lugar.
--
-- Em SQLite, `0004_page_search.sql` já cria a tabela FTS5 com
-- `tokenize = "unicode61 remove_diacritics 2"`, e insensibilidade a acento
-- vem junto, na criação, sem extensão e sem passo de normalização separado
-- para refazer depois. As duas migrações colapsam numa só, e esta fica vazia.
--
-- O arquivo é mantido, e não apagado, pelo mesmo motivo de
-- `0002_updated_at_trigger.sql`: preservar a numeração das migrações 1:1 com
-- o histórico Postgres, para que um número de migração citado num comentário,
-- num commit ou num documento continue significando a mesma coisa.
--
-- PERDA DECLARADA, e ela é real: `to_tsvector('portuguese')` fazia stemming
-- de português — procurar "correr" achava "correndo". O tokenizador
-- `unicode61` do FTS5 não faz stemming nenhum. Ganhou-se a busca sem acento
-- nativa e perdeu-se a busca por radical. Registrado em
-- `docs/MIGRACAO-SQLITE.md` para decisão posterior, não escondido.
